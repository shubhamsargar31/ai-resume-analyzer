"""
Unit test for PDF and Markdown report generation.
"""

import unittest
import os
from src.text_extractor import extract_resume_text
from src.text_cleaner import clean_text, extract_sections
from src.skill_extractor import SkillExtractor
from src.profile_extractor import extract_full_profile
from src.job_matcher import JobMatcher
from src.recommender import JobRecommender
from src.roadmap_generator import RoadmapGenerator
from src.report_generator import generate_pdf_report, generate_markdown_report

SAMPLES_DIR = os.path.join(os.path.dirname(__file__), "..", "sample_resumes")


class TestReportGenerator(unittest.TestCase):

    def test_end_to_end_report_generation(self):
        pdf_path = os.path.join(SAMPLES_DIR, "sample_data_scientist.pdf")
        raw_text, ftype = extract_resume_text(pdf_path)
        cleaned = clean_text(raw_text)
        sections = extract_sections(cleaned)
        
        skill_extractor = SkillExtractor()
        extracted = skill_extractor.extract_skills(cleaned)
        skills = extracted["detected_skills"]
        
        profile = extract_full_profile(cleaned, sections)
        matcher = JobMatcher()
        recommender = JobRecommender(matcher)
        rec = recommender.recommend_top_roles(cleaned, skills, top_n=3)
        top_roles = rec["top_recommendations"]
        
        roadmap_gen = RoadmapGenerator(skill_extractor)
        roadmap = roadmap_gen.generate_roadmap(top_roles[0], skills)

        analysis_data = {
            "candidate_name": "Alex Rivera",
            "file_name": os.path.basename(pdf_path),
            "file_type": ftype,
            "detected_skills": skills,
            "skills_by_category": extracted["skills_by_category"],
            "profile": profile,
            "top_roles": top_roles,
            "roadmap": roadmap
        }

        # Test Markdown Report
        md_report = generate_markdown_report(analysis_data)
        self.assertIn("AI Resume Analysis", md_report)
        self.assertIn("Data Scientist", md_report)

        # Test PDF Report
        pdf_bytes = generate_pdf_report(analysis_data)
        self.assertIsInstance(pdf_bytes, bytes)
        self.assertGreater(len(pdf_bytes), 1000)
        self.assertTrue(pdf_bytes.startswith(b"%PDF"), "Generated bytes should be valid PDF")


if __name__ == "__main__":
    unittest.main()
